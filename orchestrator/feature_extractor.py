# Top-level extractor
# ──────────────────────────────────────────────────────────────────────────


def extract_features(
    y_true: np.ndarray,
    y_preds: Optional[np.ndarray] = None,
    model_names: Optional[List[str]] = None,
    cfg: Optional[FeatureExtractorConfig] = None,
) -> Dict[str, float]:
    """Compute the FFORMA-style meta-feature dictionary for one dataset.

    Args:
        y_true: shape (n_windows, horizon) — validation truth.  Will be
            flattened in window order.
        y_preds: optional shape (n_windows, n_models, horizon).  If
            provided together with `model_names`, family-aware features are
            added.
        model_names: optional list of base-model names (for family detection).
        cfg: optional `FeatureExtractorConfig`.

    Returns:
        Dict[str, float] with ~25 features.  Missing/undefined values are
        NaN; downstream cosine retrieval handles NaN -> 0 imputation.
    """

    cfg = cfg or FeatureExtractorConfig()
    y2d = np.asarray(y_true, dtype=float)
    if y2d.ndim == 1:
        y2d = y2d.reshape(1, -1)
    horizon = int(y2d.shape[1])
    series = _flatten_validation(y2d)

    period = int(cfg.seasonal_period_hint) if cfg.seasonal_period_hint else max(2, min(24, horizon))
    f_t, f_s = _trend_seasonal_strength(series, period, use_stl=cfg.use_statsmodels_stl)
    lin, curv = _linearity_curvature(series)
    stab, lump = _stability_lumpiness(series, cfg.lumpiness_tile_count)

    acf = _autocorrelation(series, cfg.acf_max_lag)
    diff_series = np.diff(series)
    diff_acf = _autocorrelation(diff_series, cfg.acf_max_lag)

    feats: Dict[str, float] = {
        # Length / scale
        "length": float(series.size),
        "horizon": float(horizon),
        "n_windows": float(y2d.shape[0]),
        "mean": _safe_float(np.nanmean(series)),
        "std": _safe_float(np.nanstd(series)),
        "cv": _safe_float(np.nanstd(series) / (abs(np.nanmean(series)) + EPS)),
        # Distribution shape
        "skewness": _safe_float(_moment_skew(series)),
        "kurtosis": _safe_float(_moment_kurtosis(series)),
        # Structure (Hyndman et al. 2015)
        "trend_strength": _safe_float(f_t),
        "seasonal_strength": _safe_float(f_s),
        "linearity": _safe_float(lin),
        "curvature": _safe_float(curv),
        # Information / memory
        "spectral_entropy": _safe_float(spectral_entropy(series)),
        "hurst": _safe_float(hurst_rs(series)),
        # ACF features
        "acf1": _safe_float(acf[0]) if acf.size else float("nan"),
        "acf10_sumsq": _safe_float(np.nansum(acf ** 2)) if acf.size else float("nan"),
        "diff1_acf1": _safe_float(diff_acf[0]) if diff_acf.size else float("nan"),
        "diff1_acf10_sumsq": _safe_float(np.nansum(diff_acf ** 2)) if diff_acf.size else float("nan"),
        # Tile stats
        "stability": _safe_float(stab),
        "lumpiness": _safe_float(lump),
        "flat_spots": _safe_float(_flat_spots(series, cfg.flat_spot_segments)),
        "crossing_points_norm": _safe_float(_crossing_points(series) / max(1.0, series.size)),
        # Volatility / stationarity
        "arch_lm": _safe_float(_arch_lm(series)),
        "kpss_stat": _safe_float(_kpss_stat(series)),
    }

    if y_preds is not None and model_names is not None and len(model_names) > 0:
        feats.update(
            _family_aware_features(
                y2d, np.asarray(y_preds, dtype=float), list(model_names), cfg.family_corr_threshold
            )
        )

    return feats


def _moment_skew(x: np.ndarray) -> float:
    x = np.asarray(x, dtype=float)
    x = x[~np.isnan(x)]
    n = int(x.size)
    if n < 3:
        return float("nan")
    m = float(np.mean(x))
    s = float(np.std(x)) + EPS
    return float(np.mean(((x - m) / s) ** 3))


def _moment_kurtosis(x: np.ndarray) -> float:
    x = np.asarray(x, dtype=float)
    x = x[~np.isnan(x)]
    n = int(x.size)
    if n < 4:
        return float("nan")
    m = float(np.mean(x))
    s = float(np.std(x)) + EPS
    return float(np.mean(((x - m) / s) ** 4) - 3.0)  # excess kurtosis


# ──────────────────────────────────────────────────────────────────────────
# Identity (used by memory.py to deduplicate runs)
# ──────────────────────────────────────────────────────────────────────────


def compute_dataset_id(
    y_true: np.ndarray,
    model_names: List[str],
    explicit_id: Optional[str] = None,
) -> str:
    """Deterministic dataset identifier.

    If `explicit_id` is supplied (e.g. `M4_monthly_1234`) it is returned
    verbatim; otherwise a stable SHA-256 hex prefix derived from the data
    shape and the first window's `y_true` is returned.
    """

    if explicit_id and str(explicit_id).strip():
        return str(explicit_id).strip()
    y = np.asarray(y_true, dtype=float)
    payload = {
        "shape": [int(s) for s in y.shape],
        "models": list(map(str, model_names)),
        "first_window": [round(float(v), 6) for v in y[0].tolist()] if y.size else [],
    }
    blob = json.dumps(payload, sort_keys=True, separators=(",", ":")).encode("utf-8")
    return "ds_" + hashlib.sha256(blob).hexdigest()[:16]


def feature_vector(features: Dict[str, float], schema: Optional[List[str]] = None) -> np.ndarray:
    """Materialise a `Dict[str, float]` into a fixed-order numpy vector.

    If `schema` is provided, missing keys are filled with NaN.  Otherwise
    keys are sorted lexicographically.
    """

    keys = list(schema) if schema is not None else sorted(features.keys())
    out = np.array([features.get(k, float("nan")) for k in keys], dtype=float)
    return out
